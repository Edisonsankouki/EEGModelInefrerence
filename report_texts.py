import textwrap
import re
from copy import deepcopy

NEW_RANGES = {
    "I":   "（0-85）",
    "II":  "（85-90）",
    "III": "（90-95）",
    "IV":  "（95-100）",
}

_ROMAN = {"I": "Ⅰ", "II": "Ⅱ", "III": "Ⅲ", "IV": "Ⅳ"}

def patch_standard_text_ranges(standard_text: dict, ranges: dict = NEW_RANGES) -> dict:
    """
    把 STANDARD_TEXT 内所有:
      【Ⅰ级】（x-y）
      【Ⅱ级】（x-y）
      【Ⅲ级】（x-y）
      【Ⅳ级】（x-y）
    的括号区间替换为 ranges 指定的区间。
    返回一个新 dict，不原地修改。
    """
    out = deepcopy(standard_text)

    for metric, level_map in out.items():
        # 跳过非四级结构（例如 睡眠质量: {"正常":..., "较差":...}）
        if not isinstance(level_map, dict):
            continue
        if not any(k in level_map for k in ["I", "II", "III", "IV"]):
            continue

        for lvl_key in ["I", "II", "III", "IV"]:
            if lvl_key not in level_map:
                continue
            txt = level_map[lvl_key]
            if not isinstance(txt, str):
                continue

            roman = _ROMAN[lvl_key]
            # 匹配 “【Ⅰ级】（...）” 并仅替换括号部分
            pattern = rf"(【{roman}级】)（[^）]*）"
            repl = rf"\1{ranges[lvl_key]}"
            level_map[lvl_key] = re.sub(pattern, repl, txt, count=1)

    return out


